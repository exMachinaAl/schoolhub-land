  assert.ok(pub.res.headers.get('content-security-policy')?.includes('frame-ancestors'));
  assert.equal((await api('/api/admin/config')).res.status,401);
  assert.equal((await api('/api/admin/audit')).res.status,401);
  assert.equal((await api('/api/admin/check-links',{method:'POST'})).res.status,401);
  assert.equal((await api('/etc/passwd')).res.status,404);
  const forbidden=await api('/api/admin/login',{method:'POST',headers:{'content-type':'application/json','origin':'https://evil.example'},body:JSON.stringify({password:'Pengelola-Lokal-123!'})});
